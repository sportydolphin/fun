#!/usr/bin/env node
/**
 * update-wpbl-discord-board.mjs — a single self-editing "next games" board in Discord.
 *
 * Posts (or, on later runs, edits) ONE webhook message in a channel that always shows
 * the next few WPBL watch parties, soonest at the top, each with a live countdown and a
 * masked link that opens the native Discord event RSVP. Because it edits the same message
 * every run, the channel stays exactly one message tall — the "next game" is line one and
 * nobody has to scroll.
 *
 * Why a webhook (not a bot): a webhook is send-only HTTP — no token, no gateway, nothing
 * to keep running. The schedule it renders comes from our own Supabase mirror (wpbl_games
 * + wpbl_teams), the same source scripts/send-wpbl-game-start.mjs reads.
 *
 * Message-id persistence: the id of the message we own lives in Supabase
 * (wpbl_discord_board_state, see scripts/create_wpbl_discord_board_state.sql), NOT in a
 * hand-copied env var. First run creates the message and stores its id; every run after
 * reads that id and edits in place; if the message is ever deleted it recreates + restores.
 * DISCORD_BOARD_MESSAGE_ID is now only an optional one-time seed: if the DB has no id yet
 * but that env var is set, the existing message is adopted so no duplicate is posted.
 *
 * Usage (local):
 *   SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... \
 *   DISCORD_BOARD_WEBHOOK_URL='https://discord.com/api/webhooks/<id>/<token>' \
 *   DISCORD_WATCH_PARTY_VC_URL='https://discord.com/channels/<guild>/<voice-channel>' \
 *   DISCORD_EVENTS_URL='https://discord.gg/<invite>?event=' \
 *   [DISCORD_BOARD_MESSAGE_ID=...] \
 *   node scripts/update-wpbl-discord-board.mjs
 *
 * Required env: SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, DISCORD_BOARD_WEBHOOK_URL.
 * Optional env: DISCORD_BOARD_MESSAGE_ID (one-time seed only — see above),
 *               DISCORD_WATCH_PARTY_VC_URL,
 *               DISCORD_EVENTS_URL (fallback link when a game has no mapped event URL).
 */

import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { createClient } from '@supabase/supabase-js'
import ws from 'ws'

const HERE = dirname(fileURLToPath(import.meta.url))

// ─── Config ─────────────────────────────────────────────────────────────────

const SUPABASE_URL = process.env.SUPABASE_URL ?? process.env.VITE_SUPABASE_URL ?? ''
// Only public reads, so the anon key works — service-role not required (see mapper).
const SUPABASE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY
  ?? process.env.VITE_SUPABASE_ANON_KEY ?? process.env.SUPABASE_ANON_KEY ?? ''
const WEBHOOK_URL  = process.env.DISCORD_BOARD_WEBHOOK_URL ?? ''
const MESSAGE_ID   = process.env.DISCORD_BOARD_MESSAGE_ID ?? ''
const VC_URL       = process.env.DISCORD_WATCH_PARTY_VC_URL ?? ''
const EVENTS_URL   = process.env.DISCORD_EVENTS_URL ?? ''
// Authoritative full-season schedule (the league's official page).
const SCHEDULE_URL = process.env.WPBL_SCHEDULE_URL ?? 'https://www.womensprobaseballleague.com/schedule/'
// Link each matchup to its Discord event? That makes Discord unfurl a native event card
// under the message (can't be suppressed), which adds height. Off = clean text board.
const LINK_TO_EVENTS = true

if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.error('❌  Set SUPABASE_URL (or VITE_SUPABASE_URL) and a Supabase key (VITE_SUPABASE_ANON_KEY) before running')
  process.exit(1)
}
if (!WEBHOOK_URL) {
  console.error('❌  Set DISCORD_BOARD_WEBHOOK_URL (the full https://discord.com/api/webhooks/<id>/<token>)')
  process.exit(1)
}

// How many upcoming games the board shows.
const SHOW_COUNT = 3
// A game still counts as "on now" (and stays pinned at #1) for this long after first
// pitch, so a live watch party doesn't vanish from the board mid-game.
const LIVE_GRACE_MS = 3 * 60 * 60 * 1000
// Single Central-time hub; start_time is a flat wall clock there (mirrors the reminder sender).
const WPBL_TZ = 'America/Chicago'

/**
 * game id → the discord.gg event invite for that game's watch party.
 * Generated by scripts/map-wpbl-discord-events.mjs (which matches each event to its game
 * by start time), so you don't hand-maintain it. Anything missing falls back to
 * DISCORD_EVENTS_URL. If the file isn't there yet, we just use the fallback.
 */
let EVENT_URLS = {}
try {
  EVENT_URLS = JSON.parse(readFileSync(join(HERE, 'wpbl-event-urls.json'), 'utf8'))
} catch { /* no map generated yet — fall back to DISCORD_EVENTS_URL */ }

const supabase = createClient(SUPABASE_URL, SUPABASE_KEY, {
  auth: { autoRefreshToken: false, persistSession: false },
  realtime: { transport: ws },
})

// ─── Time + data helpers (shared shape with send-wpbl-game-start.mjs) ─────────

function todayStr(offsetDays = 0) {
  const d = new Date()
  d.setDate(d.getDate() + offsetDays)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

/** True UTC instant (epoch ms) of first pitch — treats the "H:MM AM/PM" wall clock as Central, DST-safe. */
function gameStartMs(gameDate, startTime) {
  if (!startTime) return null
  const m = String(startTime).trim().match(/^(\d{1,2}):(\d{2})\s*(AM|PM)$/i)
  if (!m) return null
  let h = parseInt(m[1], 10) % 12
  if (/pm/i.test(m[3])) h += 12
  const min = parseInt(m[2], 10)
  const [y, mo, d] = gameDate.split('-').map(Number)
  const naive = Date.UTC(y, mo - 1, d, h, min)
  const ref = new Date(naive)
  const offset = new Date(ref.toLocaleString('en-US', { timeZone: 'UTC' })).getTime()
    - new Date(ref.toLocaleString('en-US', { timeZone: WPBL_TZ })).getTime()
  return naive + offset
}

async function fetchTeamNames() {
  const { data, error } = await supabase.from('wpbl_teams').select('id, city, name')
  if (error) throw new Error(`Loading teams failed: ${error.message}`)
  const byId = new Map()
  for (const t of data ?? []) byId.set(t.id, `${t.city} ${t.name}`)
  return byId
}

function matchupLine(teamNames, game) {
  const away = teamNames.get(game.away_team_id) ?? '???'
  const home = teamNames.get(game.home_team_id) ?? '???'
  return `${away} @ ${home}`
}

function eventUrlFor(game) {
  return EVENT_URLS[game.id] ?? EVENTS_URL ?? ''
}

// ─── Embed builder ────────────────────────────────────────────────────────────

// <t:UNIX:R> renders as a live, per-viewer-timezone countdown ("in a day"). UNIX is seconds.
function tsRel(ms) { return `<t:${Math.floor(ms / 1000)}:R>` }

// Compact text board: a short header, the league schedule link, then one line per game.
// Every line leads with a dot (red = next up, white = later) so the left edge stays flush
// and "next" is indicated without unbalancing the list. Countdown is inline per game.
function buildBoardContent(games, teamNames, now) {
  const vc = VC_URL ? `, hop in [🔊 Watch Party VC](${VC_URL}) to watch together` : ''
  const header =
    `## ⚾ WPBL Watch Parties ⚾\n` +
    `📅 Full schedule: [womensprobaseballleague.com/schedule](${SCHEDULE_URL})`

  const lines = games.map((game, i) => {
    const startMs = gameStartMs(game.game_date, game.start_time)
    const dot = i === 0 ? '🔴' : '⚪'
    const name = LINK_TO_EVENTS && eventUrlFor(game)
      ? `[${matchupLine(teamNames, game)}](${eventUrlFor(game)})`
      : matchupLine(teamNames, game)
    const when = startMs == null ? ''
      : startMs <= now ? ' · 🟢 **live now**'
      : ` · ${tsRel(startMs)}`
    return `${dot} ${name}${when}`
  })

  return `${header}\n\n${lines.join('\n')}`
}

// ─── Discord webhook I/O ────────────────────────────────────────────────────

async function createMessage(payload) {
  // ?wait=true makes Discord return the created message (so we learn its id).
  const res = await fetch(`${WEBHOOK_URL}?wait=true`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })
  if (!res.ok) throw new Error(`Create failed (${res.status}): ${await res.text()}`)
  return res.json()
}

// Returns { gone: true } if Discord no longer has the message (deleted by hand, or the
// stored id is stale) so the caller can transparently recreate it. Other failures throw.
async function editMessage(id, payload) {
  const res = await fetch(`${WEBHOOK_URL}/messages/${id}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })
  if (res.status === 404) return { gone: true }
  if (!res.ok) throw new Error(`Edit failed (${res.status}): ${await res.text()}`)
  return { gone: false }
}

// ─── Message-id persistence (Supabase) ──────────────────────────────────────
// The board owns exactly one Discord message; its id lives in wpbl_discord_board_state
// so every run edits that message instead of posting a new one. Read/written with the
// service role in CI (bypasses RLS). Read/write failures degrade gracefully — worst case
// the board posts a fresh message — rather than aborting the run.

// Returns { ok, id }: ok=false means the store is unreadable (e.g. the table hasn't been
// created), which the caller treats as "persistence is broken" and refuses to create a new
// message — otherwise it would post an un-rememberable board on every 15-minute run.
async function loadStoredMessageId() {
  const { data, error } = await supabase
    .from('wpbl_discord_board_state')
    .select('message_id')
    .eq('id', 'board')
    .maybeSingle()
  if (error) { console.warn(`⚠️  Could not read stored board id: ${error.message}`); return { ok: false, id: '' } }
  return { ok: true, id: data?.message_id ?? '' }
}

async function storeMessageId(id) {
  const { error } = await supabase
    .from('wpbl_discord_board_state')
    .upsert({ id: 'board', message_id: id, updated_at: new Date().toISOString() })
  if (error) { console.error(`⚠️  Could not persist board id ${id}: ${error.message}`); return false }
  return true
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  const now = Date.now()

  // Pull a small forward window of non-final games. Order in JS by true first-pitch
  // instant, keep anything still upcoming (or live within the grace window), take N.
  const { data: rows, error } = await supabase
    .from('wpbl_games')
    .select('id, game_date, start_time, status, home_team_id, away_team_id')
    .neq('status', 'final')
    .gte('game_date', todayStr(-1))   // -1 day so a late game near UTC midnight still shows
    .lte('game_date', todayStr(30))
    .order('game_date', { ascending: true })
    .order('start_time', { ascending: true })
  if (error) throw new Error(`Loading games failed: ${error.message}`)

  const upcoming = (rows ?? [])
    .map(g => ({ ...g, _startMs: gameStartMs(g.game_date, g.start_time) }))
    .filter(g => g._startMs != null && g._startMs > now - LIVE_GRACE_MS)
    .sort((a, b) => a._startMs - b._startMs)
    .slice(0, SHOW_COUNT)

  const teamNames = await fetchTeamNames()

  const payload = {
    // Keep the webhook from pinging anyone when it edits.
    allowed_mentions: { parse: [] },
    // Clear any author embed from earlier versions. (This does NOT remove the event-card
    // unfurls — those are what we want here — it only drops embeds we set ourselves.)
    embeds: [],
    content: upcoming.length
      ? buildBoardContent(upcoming, teamNames, now)
      : `## ⚾ WPBL Watch Parties\nNo games scheduled right now — check back soon! ⚾\n📅 Full schedule: [womensprobaseballleague.com/schedule](${SCHEDULE_URL})`,
  }

  // Source of truth for which message to edit is the DB. DISCORD_BOARD_MESSAGE_ID is now
  // only a one-time seed: if the DB has no id yet but the old repo variable is still set,
  // adopt that existing message (and persist it) so this migration doesn't post a duplicate.
  const stored = await loadStoredMessageId()
  let messageId = stored.id
  let adopting = false
  if (!messageId && MESSAGE_ID) { messageId = MESSAGE_ID; adopting = true }

  if (messageId) {
    const { gone } = await editMessage(messageId, payload)
    if (!gone) {
      if (adopting) await storeMessageId(messageId)   // adopt the seeded id into the DB
      console.log(`✅ Edited board message ${messageId} — showing ${upcoming.length} game(s).`)
      return
    }
    console.warn(`⚠️  Board message ${messageId} no longer exists — creating a fresh one.`)
  }

  // Guard: never post a message we can't remember. If the store is unreadable (missing
  // table, bad creds), creating here would spawn a brand-new board on every 15-minute run —
  // exactly the duplicate-spam this persistence was added to stop. Fail loudly instead so
  // the workflow goes red and nothing is posted until wpbl_discord_board_state exists.
  if (!stored.ok) {
    throw new Error(
      'wpbl_discord_board_state is unreadable (has scripts/create_wpbl_discord_board_state.sql been run?) — ' +
      'refusing to CREATE a board we cannot persist, which would duplicate every run.'
    )
  }

  const msg = await createMessage(payload)
  const persisted = await storeMessageId(msg.id)
  if (!persisted) throw new Error(`Created board message ${msg.id} but FAILED to persist its id — aborting so the next run doesn't duplicate. Fix wpbl_discord_board_state writes.`)
  console.log(`✅ Created board message ${msg.id} — showing ${upcoming.length} game(s). Persisted for future edits.`)
}

main().catch(err => { console.error('Fatal:', err); process.exit(1) })
