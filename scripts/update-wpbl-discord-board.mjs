#!/usr/bin/env node
/**
 * update-wpbl-discord-board.mjs — a single self-editing "next games" board in Discord.
 *
 * Posts (or, on later runs, edits) ONE webhook message in a channel that always shows
 * the next few WPBL watch parties, soonest at the top, each with a live countdown and a
 * masked link that opens the native Discord event RSVP. Because it edits the same message
 * every run, the channel stays exactly one message tall — the "next game" is line one and
 * nobody has to scroll.
 *
 * Why a webhook (not a bot): a webhook is send-only HTTP — no token, no gateway, nothing
 * to keep running. The schedule it renders comes from our own Supabase mirror (wpbl_games
 * + wpbl_teams), the same source scripts/send-wpbl-game-start.mjs reads.
 *
 * Message-id persistence: the id of the message we own lives in Supabase
 * (wpbl_discord_board_state, see scripts/create_wpbl_discord_board_state.sql), NOT in a
 * hand-copied env var. First run creates the message and stores its id; every run after
 * reads that id and edits in place; if the message is ever deleted it recreates + restores.
 * DISCORD_BOARD_MESSAGE_ID is now only an optional one-time seed: if the DB has no id yet
 * but that env var is set, the existing message is adopted so no duplicate is posted.
 *
 * Usage (local):
 *   SUPABASE_URL=... SUPABASE_SERVICE_ROLE_KEY=... \
 *   DISCORD_BOARD_WEBHOOK_URL='https://discord.com/api/webhooks/<id>/<token>' \
 *   DISCORD_EVENTS_URL='https://discord.com/channels/<guild>/<events-channel>' \
 *   [DISCORD_BOARD_MESSAGE_ID=...] \
 *   node scripts/update-wpbl-discord-board.mjs
 *
 * Required env: SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY, DISCORD_BOARD_WEBHOOK_URL.
 * Optional env: DISCORD_BOARD_MESSAGE_ID (one-time seed only — see above),
 *               DISCORD_EVENTS_URL (fallback link when a game has no mapped event URL;
 *               it must be a link that WORKS on its own, since it is used verbatim. An
 *               invite ending in a bare '?event=' resolves to the invite and no event).
 */

import { readFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join } from 'node:path'
import { createClient } from '@supabase/supabase-js'
import ws from 'ws'
// The board and the postseason event sync have to agree on how a bracket slot is named in
// wpbl-event-urls.json, so the format is defined once, there, and imported here.
import { postseasonSlotKey } from './sync-wpbl-discord-postseason.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))

// ─── Config ─────────────────────────────────────────────────────────────────

const SUPABASE_URL = process.env.SUPABASE_URL ?? process.env.VITE_SUPABASE_URL ?? ''
// Only public reads, so the anon key works — service-role not required (see mapper).
const SUPABASE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY
  ?? process.env.VITE_SUPABASE_ANON_KEY ?? process.env.SUPABASE_ANON_KEY ?? ''
const WEBHOOK_URL  = process.env.DISCORD_BOARD_WEBHOOK_URL ?? ''
const MESSAGE_ID   = process.env.DISCORD_BOARD_MESSAGE_ID ?? ''
const EVENTS_URL   = process.env.DISCORD_EVENTS_URL ?? ''
// Authoritative full-season schedule (the league's official page).
const SCHEDULE_URL = process.env.WPBL_SCHEDULE_URL ?? 'https://www.womensprobaseballleague.com/schedule/'
// Link each matchup to its Discord event? That makes Discord unfurl a native event card
// under the message (can't be suppressed), which adds height. Off = clean text board.
const LINK_TO_EVENTS = true
// Build the board and print it, touching Discord not at all. The other Discord jobs offer this
// as a workflow input; this one had no way to see what it was about to say, which matters most
// on the change that taught it about the postseason.
const DRY_RUN = process.argv.includes('--dry-run')


// How many upcoming games the board shows.
const SHOW_COUNT = 3
// A game still counts as "on now" (and stays pinned at #1) for this long after first
// pitch, so a live watch party doesn't vanish from the board mid-game.
const LIVE_GRACE_MS = 3 * 60 * 60 * 1000
// Single Central-time hub; start_time is a flat wall clock there (mirrors the reminder sender).
const WPBL_TZ = 'America/Chicago'

/**
 * api_game_id → the Discord event link for that game's watch party.
 * Generated by scripts/map-wpbl-discord-events.mjs (which matches each event to its game
 * by start time), so you don't hand-maintain it. Anything missing falls back to
 * DISCORD_EVENTS_URL. If the file isn't there yet, we just use the fallback.
 *
 * Keyed on api_game_id (the league feed's own id), NOT on wpbl_games.id. The ingest
 * deletes phantom duplicates of a game by api_game_id and reinserts the real one later,
 * which mints a FRESH uuid, so a uuid-keyed map quietly loses its entry a few days before
 * each game and the board falls back to the generic link with nothing logged. api_game_id
 * is the upsert's conflict key, so it survives that churn by construction.
 */
let EVENT_URLS = {}
try {
  EVENT_URLS = JSON.parse(readFileSync(join(HERE, 'wpbl-event-urls.json'), 'utf8'))
} catch { /* no map generated yet — fall back to DISCORD_EVENTS_URL */ }

/**
 * The Supabase client, built on first use rather than at import.
 *
 * `createClient` throws on an empty URL, so a module-scope client made this file impossible to
 * import without credentials, which is what kept its pure helpers out of a test. Lazily it is
 * only ever built by `main`, which has already checked the two variables by then.
 */
let _supabase = null
function db() {
  if (!_supabase) {
    _supabase = createClient(SUPABASE_URL, SUPABASE_KEY, {
      auth: { autoRefreshToken: false, persistSession: false },
      realtime: { transport: ws },
    })
  }
  return _supabase
}

// ─── Time + data helpers (shared shape with send-wpbl-game-start.mjs) ─────────

function todayStr(offsetDays = 0) {
  const d = new Date()
  d.setDate(d.getDate() + offsetDays)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

/** True UTC instant (epoch ms) of first pitch — treats the "H:MM AM/PM" wall clock as Central, DST-safe. */
function gameStartMs(gameDate, startTime) {
  if (!startTime) return null
  const m = String(startTime).trim().match(/^(\d{1,2}):(\d{2})\s*(AM|PM)$/i)
  if (!m) return null
  let h = parseInt(m[1], 10) % 12
  if (/pm/i.test(m[3])) h += 12
  const min = parseInt(m[2], 10)
  const [y, mo, d] = gameDate.split('-').map(Number)
  const naive = Date.UTC(y, mo - 1, d, h, min)
  const ref = new Date(naive)
  const offset = new Date(ref.toLocaleString('en-US', { timeZone: 'UTC' })).getTime()
    - new Date(ref.toLocaleString('en-US', { timeZone: WPBL_TZ })).getTime()
  return naive + offset
}

async function fetchTeamNames() {
  const { data, error } = await db().from('wpbl_teams').select('id, city, name')
  if (error) throw new Error(`Loading teams failed: ${error.message}`)
  const byId = new Map()
  for (const t of data ?? []) byId.set(t.id, `${t.city} ${t.name}`)
  return byId
}

export function matchupLine(teamNames, game) {
  const away = teamNames.get(game.away_team_id)
  const home = teamNames.get(game.home_team_id)
  // A POSTSEASON GAME MAY HAVE NO CLUBS YET, which is not a data fault: the championship's
  // five fixtures are published weeks before anybody knows who is in them. "??? @ ???" was
  // the old answer to a missing club and it is the wrong one here, because the round and the
  // game number ARE the name of that fixture until the semifinals fill it in.
  if (!away || !home) return game.series_label ?? `${away ?? '???'} @ ${home ?? '???'}`
  return `${away} @ ${home}`
}

function eventUrlFor(game) {
  // The slot key first for a fixture the stats feed has never heard of, then the feed's own id,
  // then the generic events link. A postseason game has an event long before it has an
  // api_game_id (see postseasonSlotKey), and without the first lookup every one of them fell
  // back to the same generic link, so a board listing three different games pointed all three
  // at one event.
  return EVENT_URLS[game.slot_key] ?? EVENT_URLS[game.api_game_id] ?? EVENTS_URL ?? ''
}

// ─── The postseason, which the feed does not carry ────────────────────────────

/** Games a club must win to take the round. Best of three, then best of five.
 *
 *  A LITERAL HERE AND NOT AN IMPORT, because this is a plain .mjs and the one definition
 *  (`BEST_OF` / `winsNeeded` in src/wpbl/derive/series.ts) is TypeScript the app bundles. Keep
 *  the two in step: this decides which fixtures are marked as only-if-necessary, so a league
 *  that lengthened a round would have this board promising a game that may never be played. */
export const WINS_NEEDED = { semifinal: 2, championship: 3 }

/** "Semifinal A · Game 2", or "Championship · Game 4". The name of a fixture that has no clubs
 *  in it yet, and the suffix on one that does. */
export function seriesLabel(row) {
  if (!row.round || !row.game_number) return null
  const round = row.round === 'championship'
    ? 'Championship'
    : `Semifinal${row.series_key ? ` ${row.series_key}` : ''}`
  return `${round} · Game ${row.game_number}`
}

/**
 * The postseason fixtures, from the league's own WEBSITE calendar.
 *
 * WHY THIS EXISTS AT ALL. The board reads `wpbl_games`, which is the STATS feed's mirror, and
 * that feed will not carry a game row without two clubs on it: measured Sep 7, 2026, it held
 * nothing at all from Sep 7 onward while the postseason ran Sep 9 to Sep 22. So the board was
 * going to post "No games scheduled right now" for the entire postseason, on a server whose
 * whole purpose is watch parties, through the eleven games anybody would actually turn up for.
 *
 * `wpbl_site_games` is the league's website calendar (see the migration that adds it), which had
 * all eleven with dates, first-pitch times and, for the six semifinal games, which club bats
 * last. It is not a second opinion about anything the stats feed carries; it answers the one
 * question the feed cannot yet answer, and it retires itself fixture by fixture as the feed
 * picks each one up, which is what the de-duplication below is for.
 */
async function fetchPostseasonRows() {
  const { data, error } = await db()
    .from('wpbl_site_games')
    .select('event_id, game_date, start_time, status, round, series_key, game_number, home_team_id, away_team_id')
    .eq('status', 'scheduled')
    .gte('game_date', todayStr(-1))
    .lte('game_date', todayStr(30))
  if (error) {
    // Not fatal. A board that loses the postseason is worse than one that loses it silently
    // is worse than no board at all, so this degrades to the feed's own rows and says so.
    console.warn(`⚠️  Loading the site calendar failed (${error.message}) — postseason fixtures omitted.`)
    return []
  }
  return (data ?? []).map(siteRowToGame)
}

/** One website-calendar row as the board's own game shape. Exported because every rule that
 *  could go wrong quietly lives in here: which fixture is conditional, what a clubless one is
 *  called, and which watch party it links to. */
export function siteRowToGame(r) {
  return ({
    // No api_game_id: these rows are not the stats feed's, so they have no event mapping and
    // fall back to the generic events link, which is the right answer for a fixture the watch
    // party has not been created for yet.
    api_game_id: null,
    id: `site:${r.event_id}`,
    game_date: r.game_date,
    start_time: r.start_time,
    home_team_id: r.home_team_id,
    away_team_id: r.away_team_id,
    series_label: seriesLabel(r),
    slot_key: postseasonSlotKey(
      r.round === 'championship' ? 'final' : r.series_key ? `semi-${String(r.series_key).toLowerCase()}` : null,
      r.game_number),
    // Derived from the format rather than read off the title: the website marks the
    // championship's last two "if needed" and marks no semifinal decider at all, so trusting
    // its wording would promise a Game 3 that only happens half the time.
    ifNecessary: !!(r.round && r.game_number && r.game_number > (WINS_NEEDED[r.round] ?? 99)),
  })
}

/** One key per fixture, so a site row disappears the moment the stats feed carries the same
 *  game. Date plus the unordered pair of clubs, because that is all the two sources share: the
 *  feed has no event id and the website has no api_game_id. A fixture with no clubs cannot
 *  collide with anything, so it keys on itself. */
export function fixtureKey(g) {
  if (!g.home_team_id || !g.away_team_id) return g.id
  return `${g.game_date}|${[g.home_team_id, g.away_team_id].sort().join('-')}`
}

// ─── Embed builder ────────────────────────────────────────────────────────────

// <t:UNIX:R> renders as a live, per-viewer-timezone countdown ("in a day"). UNIX is seconds.
function tsRel(ms) { return `<t:${Math.floor(ms / 1000)}:R>` }

/**
 * Two lines, and a third that was removed on purpose.
 *
 * NO ROOM LINK. The board carried "Watch along in Game Day Watch Party" on every render,
 * which is a link to the channel the board is posted in: the reader is already there. It
 * cost a line of a message whose whole point is being exactly as tall as its games, and
 * every game line already links to its own event, which is the thing worth tapping.
 *
 * THE SCHEDULE URL IS WRAPPED IN ANGLE BRACKETS INSIDE THE MARKDOWN LINK. Discord unfurls
 * the target of a masked link like any other, so this one line grew a website preview card
 * under a board that is meant to be short. `<>` suppresses that unfurl and nothing else:
 * the link still reads as text and still opens. Do not tidy the brackets out, and do not
 * reach for the message's SUPPRESS_EMBEDS flag instead, which would also kill the event
 * cards the game links exist to produce.
 */
function boardHeader() {
  return [
    `## ⚾ WPBL Watch Parties ⚾`,
    `📅 Full schedule: [womensprobaseballleague.com/schedule](<${SCHEDULE_URL}>)`,
  ].join('\n')
}

// Compact text board: a short header, the league schedule link, then one line per game.
// Every line leads with a dot (red = next up, white = later) so the left edge stays flush
// and "next" is indicated without unbalancing the list. Countdown is inline per game.
function buildBoardContent(games, teamNames, now) {
  const header = boardHeader()

  const lines = games.map((game, i) => {
    const startMs = gameStartMs(game.game_date, game.start_time)
    const dot = i === 0 ? '🔴' : '⚪'
    const name = LINK_TO_EVENTS && eventUrlFor(game)
      ? `[${matchupLine(teamNames, game)}](${eventUrlFor(game)})`
      : matchupLine(teamNames, game)
    const when = startMs == null ? ''
      : startMs <= now ? ' · 🟢 **live now**'
      : ` · ${tsRel(startMs)}`
    // The round, on a line that already names the clubs, and the caveat on a fixture that may
    // never be played. A board that lists a Game 3 without saying so is promising a game half
    // of these series will not have.
    const round = game.series_label && teamNames.get(game.home_team_id) && teamNames.get(game.away_team_id)
      ? ` · ${game.series_label}` : ''
    const maybe = game.ifNecessary ? ' *(if needed)*' : ''
    return `${dot} ${name}${round}${when}${maybe}`
  })

  return `${header}\n\n${lines.join('\n')}`
}

// ─── Discord webhook I/O ────────────────────────────────────────────────────

async function createMessage(payload) {
  // ?wait=true makes Discord return the created message (so we learn its id).
  const res = await fetch(`${WEBHOOK_URL}?wait=true`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })
  if (!res.ok) throw new Error(`Create failed (${res.status}): ${await res.text()}`)
  return res.json()
}

// Returns { gone: true } if Discord no longer has the message (deleted by hand, or the
// stored id is stale) so the caller can transparently recreate it. Other failures throw.
async function editMessage(id, payload) {
  const res = await fetch(`${WEBHOOK_URL}/messages/${id}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  })
  if (res.status === 404) return { gone: true }
  if (!res.ok) throw new Error(`Edit failed (${res.status}): ${await res.text()}`)
  return { gone: false }
}

// ─── Message-id persistence (Supabase) ──────────────────────────────────────
// The board owns exactly one Discord message; its id lives in wpbl_discord_board_state
// so every run edits that message instead of posting a new one. Read/written with the
// service role in CI (bypasses RLS). Read/write failures degrade gracefully — worst case
// the board posts a fresh message — rather than aborting the run.

// Returns { ok, id }: ok=false means the store is unreadable (e.g. the table hasn't been
// created), which the caller treats as "persistence is broken" and refuses to create a new
// message — otherwise it would post an un-rememberable board on every 15-minute run.
async function loadStoredMessageId() {
  const { data, error } = await db()
    .from('wpbl_discord_board_state')
    .select('message_id')
    .eq('id', 'board')
    .maybeSingle()
  if (error) { console.warn(`⚠️  Could not read stored board id: ${error.message}`); return { ok: false, id: '' } }
  return { ok: true, id: data?.message_id ?? '' }
}

async function storeMessageId(id) {
  const { error } = await db()
    .from('wpbl_discord_board_state')
    .upsert({ id: 'board', message_id: id, updated_at: new Date().toISOString() })
  if (error) { console.error(`⚠️  Could not persist board id ${id}: ${error.message}`); return false }
  return true
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  // CHECKED HERE AND NOT AT MODULE SCOPE. These used to exit(1) on import, which meant the pure
  // helpers above could not be reached by a test without the process dying: the rules that turn
  // a postseason fixture into a board line are exactly the ones worth pinning, and they were
  // unreachable.
  if (!SUPABASE_URL || !SUPABASE_KEY) {
    console.error('❌  Set SUPABASE_URL (or VITE_SUPABASE_URL) and a Supabase key (VITE_SUPABASE_ANON_KEY) before running')
    process.exit(1)
  }
  if (!WEBHOOK_URL && !DRY_RUN) {
    console.error('❌  Set DISCORD_BOARD_WEBHOOK_URL (the full https://discord.com/api/webhooks/<id>/<token>)')
    process.exit(1)
  }

  const now = Date.now()

  // Pull a small forward window of non-final games. Order in JS by true first-pitch
  // instant, keep anything still upcoming (or live within the grace window), take N.
  const { data: rows, error } = await db()
    .from('wpbl_games')
    .select('id, api_game_id, game_date, start_time, status, home_team_id, away_team_id')
    .neq('status', 'final')
    .gte('game_date', todayStr(-1))   // -1 day so a late game near UTC midnight still shows
    .lte('game_date', todayStr(30))
    .order('game_date', { ascending: true })
    .order('start_time', { ascending: true })
  if (error) throw new Error(`Loading games failed: ${error.message}`)

  // The stats feed's rows first, then the website calendar's postseason fixtures for anything
  // the feed does not carry. The feed wins every collision: its row has an api_game_id, which is
  // what the Discord event mapping is keyed on, so preferring it is what keeps a fixture's watch
  // party link attached the day the feed picks that fixture up.
  const postseason = await fetchPostseasonRows()
  const byFixture = new Map()
  for (const g of rows ?? []) byFixture.set(fixtureKey(g), g)
  for (const g of postseason) if (!byFixture.has(fixtureKey(g))) byFixture.set(fixtureKey(g), g)

  // THE FEED WINS THE COLLISION ON IDENTITY AND LOSES IT ON THE CLOCK. Everything above is
  // about keeping the row that carries an api_game_id, and that is still right. But the feed
  // publishes a first pitch once and then stops touching a scheduled row: on Sep 10, 2026 it
  // had that night's semifinal an hour early for three days while the calendar had it right,
  // and this board's whole job is a countdown. Same rule as src/wpbl/startTimes.ts.
  for (const g of postseason) {
    const kept = byFixture.get(fixtureKey(g))
    if (kept && kept !== g && kept.status === 'scheduled' && g.start_time && g.start_time !== kept.start_time) {
      console.log(`  ⏰  ${g.away_team_id}@${g.home_team_id}: feed says ${kept.start_time}, league says ${g.start_time}`)
      kept.start_time = g.start_time
    }
  }

  const upcoming = [...byFixture.values()]
    .map(g => ({ ...g, _startMs: gameStartMs(g.game_date, g.start_time) }))
    .filter(g => g._startMs != null && g._startMs > now - LIVE_GRACE_MS)
    .sort((a, b) => a._startMs - b._startMs)
    .slice(0, SHOW_COUNT)

  const teamNames = await fetchTeamNames()

  const payload = {
    // Keep the webhook from pinging anyone when it edits.
    allowed_mentions: { parse: [] },
    // Clear any author embed from earlier versions. (This does NOT remove the event-card
    // unfurls — those are what we want here — it only drops embeds we set ourselves.)
    embeds: [],
    content: upcoming.length
      ? buildBoardContent(upcoming, teamNames, now)
      : `${boardHeader()}

No games scheduled right now. Check back soon! ⚾`,
  }

  if (DRY_RUN) {
    console.log(`--- dry run: ${upcoming.length} game(s) ---
${payload.content}
--- end ---`)
    return
  }

  // Source of truth for which message to edit is the DB. DISCORD_BOARD_MESSAGE_ID is now
  // only a one-time seed: if the DB has no id yet but the old repo variable is still set,
  // adopt that existing message (and persist it) so this migration doesn't post a duplicate.
  const stored = await loadStoredMessageId()
  let messageId = stored.id
  let adopting = false
  if (!messageId && MESSAGE_ID) { messageId = MESSAGE_ID; adopting = true }

  if (messageId) {
    const { gone } = await editMessage(messageId, payload)
    if (!gone) {
      if (adopting) await storeMessageId(messageId)   // adopt the seeded id into the DB
      console.log(`✅ Edited board message ${messageId} — showing ${upcoming.length} game(s).`)
      return
    }
    console.warn(`⚠️  Board message ${messageId} no longer exists — creating a fresh one.`)
  }

  // Guard: never post a message we can't remember. If the store is unreadable (missing
  // table, bad creds), creating here would spawn a brand-new board on every 15-minute run —
  // exactly the duplicate-spam this persistence was added to stop. Fail loudly instead so
  // the workflow goes red and nothing is posted until wpbl_discord_board_state exists.
  if (!stored.ok) {
    throw new Error(
      'wpbl_discord_board_state is unreadable (has scripts/create_wpbl_discord_board_state.sql been run?) — ' +
      'refusing to CREATE a board we cannot persist, which would duplicate every run.'
    )
  }

  const msg = await createMessage(payload)
  const persisted = await storeMessageId(msg.id)
  if (!persisted) throw new Error(`Created board message ${msg.id} but FAILED to persist its id — aborting so the next run doesn't duplicate. Fix wpbl_discord_board_state writes.`)
  console.log(`✅ Created board message ${msg.id} — showing ${upcoming.length} game(s). Persisted for future edits.`)
}

// Guarded, like the two Discord scripts beside it, so the pure helpers above can be imported
// by a test without the board trying to post itself.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(err => { console.error('Fatal:', err); process.exit(1) })
}
